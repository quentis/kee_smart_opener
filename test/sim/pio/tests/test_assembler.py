"""The Python assembler must produce what the Rust `pio` assembler (behind embassy-rp's pio_asm!)
produces. golden_opcodes.json is generated by tools/golden-gen."""

import json
from collections import deque
from pathlib import Path

import pioemu
import pytest
from pioemu import State

from pio_sim.assembler import AssemblerError, MovStatus, ShiftConfig, assemble

GOLDEN = json.loads(Path(__file__).with_name("golden_opcodes.json").read_text())


@pytest.mark.parametrize("entry", GOLDEN, ids=[entry["name"] for entry in GOLDEN])
def test_matches_rust_pio_assembler(entry):
    program = assemble(entry["source"])

    assert program.code == entry["code"]
    assert (program.wrap_target, program.wrap_top) == (entry["wrap_target"], entry["wrap_top"])
    assert program.origin == entry["origin"]
    assert (program.side_set_count, program.side_set_opt, program.side_set_pindirs) == (
        entry["side_set_count"],
        entry["side_set_opt"],
        entry["side_set_pindirs"],
    )
    assert program.public_defines == entry["public_defines"]


@pytest.mark.parametrize(
    "source",
    [
        ".side_set 1",  # no instructions
        ".side_set 1\nnop",  # 'side' is required
        ".side_set 1\nnop side 2",
        ".side_set 2\nnop side 0 [8]",  # delay does not fit next to the side-set bits
        ".side_set 1 opt\nnop [8]",
        ".side_set 6",
        "nop\n.side_set 1",
        "nop side 1",
        ".wrap_target\nnop",  # wrap_target without wrap
        ".wrap\nnop",
        ".wrap_target\n.wrap_target\nnop\n.wrap",
        ".word 0x1234",
        ".clock_div 0\nnop",
        ".clock_div 65536\nnop",
        ".clock_div\nnop",
        "nop\n.fifo tx",  # must precede the instructions
        "nop\n.out 8",
        ".fifo bogus\nnop",
        ".fifo txput\n.in 32 auto\nnop",  # autopush does not work with a FIFO configured for put/get
        ".set 6\nnop",
        ".in 0\nnop",
        ".out 33\nnop",
        ".out 8 right auto 0\nnop",
        ".in 8 auto auto\nnop",
        ".mov_status\nnop",
        ".mov_status txfifo 3\nnop",
        ".mov_status txfifo < 32\nnop",
        ".mov_status irq set 8\nnop",
        ".pio_version 2\nnop",
        ".frobnicate 1\nnop",
        "irq 8",
        "irq 1 rel next",
        "wait 1 pin 1 rel",
        "wait 1 irq 8",
        "wait 2 gpio 1",
        "wait 1 jmppin",
        "mov rxfifo[y], x",
        "mov x, rxfifo[0]",
        "mov x, osr, y",
        "mov status, x",
        "push block iffull",
        "pull noblock ifempty",
        "set x, -1",
        "jmp x 3",
        "jmp x!=x 3",
        "nop side",
        "nop [1] [2]",
        "a:\na:\nnop",  # label defined twice
        "in:\nnop",  # reserved word
        ".define X Y\nnop",  # unknown define
        "nop % 3",
        "jmp nowhere",
        "jmp 32",
        "in x, 33",
        "set x, 32",
        "push block noblock",
        "mov x, bogus",
        "nop [32]",
        "frobnicate",
        "",
    ],
)
def test_rejects_what_it_cannot_assemble(source):
    with pytest.raises(AssemblerError):
        assemble(source)


SETTINGS = """
.pio_version 1
.side_set 1 opt pindirs
.clock_div 30000
.fifo tx
.in 8 left auto 16
.out 32 right auto 24
.set 3
.mov_status txfifo < 3
"""


def test_settings_directives_do_not_change_the_opcodes():
    body = ".wrap_target\nset x, 1 side 1\nmov x, ~status\n.wrap\n"

    program = assemble(SETTINGS + body)

    assert program.code == assemble(".side_set 1 opt\n" + body).code
    assert program.pio_version == 1
    assert (program.side_set_count, program.side_set_opt, program.side_set_pindirs) == (1, True, True)
    assert program.clock_div == 30000
    assert program.fifo == "tx"
    assert program.in_shift == ShiftConfig(count=8, shift_right=False, auto=True, threshold=16)
    assert program.out_shift == ShiftConfig(count=32, shift_right=True, auto=True, threshold=24)
    assert program.set_count == 3
    assert program.mov_status == MovStatus("txfifo", 3)


def test_settings_default_to_the_pioasm_defaults():
    program = assemble(".in 5\n.out 0 manual\n.clock_div 1.5\nnop")

    assert program.in_shift == ShiftConfig(count=5, shift_right=True, auto=False, threshold=32)
    assert program.out_shift == ShiftConfig(count=0, shift_right=True, auto=False, threshold=32)
    assert program.clock_div == 1.5
    assert assemble("nop").mov_status is None


@pytest.mark.parametrize(
    "line, expected",
    [
        (".mov_status txfifo < 4", MovStatus("txfifo", 4)),
        (".mov_status rxfifo < 1", MovStatus("rxfifo", 1)),
        (".mov_status irq set 2", MovStatus("irq", 2)),
        (".mov_status irq prev set 2", MovStatus("irq", 10)),
        (".mov_status irq next set 2", MovStatus("irq", 18)),
    ],
)
def test_mov_status_forms(line, expected):
    assert assemble(line + "\nnop").mov_status == expected


def test_emulator_options_configure_pioemu():
    program = assemble(".side_set 1 opt\n.out 16 left auto 8\n.in 32 auto 12\n.set 2\n.mov_status rxfifo < 2\nnop side 1")

    options = program.emulator_options()

    assert options == {
        "wrap_target": 0,
        "wrap_top": 0,
        "side_set_count": 1,
        "side_set_opt": True,
        "auto_push": True,
        "push_threshold": 12,
        "shift_isr_right": True,
        "auto_pull": True,
        "pull_threshold": 8,
        "shift_osr_right": False,
        "out_count": 16,
        "set_count": 2,
        "status_sel": 1,
        "status_n": 2,
    }


def test_mov_status_reaches_pioemu():
    """`mov x, status` is all ones while the TX FIFO holds fewer words than `.mov_status txfifo < N`"""
    program = assemble(".mov_status txfifo < 2\nmov x, status\npull noblock\nmov y, status")

    generator = pioemu.emulate(
        program.code,
        stop_when=lambda opcode, state: state.clock >= 3,  # the program wraps, so it would never end
        initial_state=State(transmit_fifo=deque([5, 6])),
        **program.emulator_options(),
    )
    states = [after for _, after in generator]

    assert states[0].x_register == 0  # two words: not fewer than two
    assert states[2].y_register == 0xFFFF_FFFF  # one word left


def test_irq_mov_status_has_no_pioemu_equivalent():
    with pytest.raises(ValueError):
        assemble(".mov_status irq set 1\nnop").emulator_options()


def test_lang_opts_are_collected_per_language():
    program = assemble(
        '.lang_opt sim clock_hz = 5000000\n.lang_opt sim in_base = 0\n.lang_opt python sideset_init = pico.PIO.OUT_LOW\n'
        '.lang_opt c name = "quoted value"\n.lang_opt sim in_base = 1\nnop'
    )

    assert program.lang_opts == {
        "sim": {"clock_hz": "5000000", "in_base": "1"},  # the last one wins
        "python": {"sideset_init": "pico.PIO.OUT_LOW"},
        "c": {"name": "quoted value"},
    }
    assert assemble("nop").lang_opts == {}


@pytest.mark.parametrize("line", [".lang_opt", ".lang_opt sim", ".lang_opt sim x", ".lang_opt sim x =", ".lang_opt sim x=1"])
def test_malformed_lang_opt_is_rejected(line):
    with pytest.raises(AssemblerError):
        assemble(line + "\nnop")
