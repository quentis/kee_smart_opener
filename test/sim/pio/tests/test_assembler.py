"""The Python assembler must produce what the Rust `pio` assembler (behind embassy-rp's pio_asm!)
produces. golden_opcodes.json is generated by tools/golden-gen."""

import json
from pathlib import Path

import pytest

from pio_sim.assembler import AssemblerError, assemble

GOLDEN = json.loads(Path(__file__).with_name("golden_opcodes.json").read_text())


@pytest.mark.parametrize("entry", GOLDEN, ids=[entry["name"] for entry in GOLDEN])
def test_matches_rust_pio_assembler(entry):
    program = assemble(entry["source"])

    assert program.code == entry["code"]
    assert (program.wrap_target, program.wrap_top) == (entry["wrap_target"], entry["wrap_top"])


@pytest.mark.parametrize(
    "source",
    [
        "irq set 1",  # pioemu has no IRQ model
        ".side_set 1",
        "jmp nowhere",
        "jmp 32",
        "in x, 33",
        "set x, 32",
        "push block noblock",
        "mov x, bogus",
        "nop [32]",
        "frobnicate",
        "",
    ],
)
def test_rejects_what_it_cannot_assemble(source):
    with pytest.raises(AssemblerError):
        assemble(source)
